TABLES = {"es": SPANISH, "de": GERMAN, "fr": FRENCH, "pt": PORTUGUESE}


def language_code(language):
    """Anki's language as its primary subtag: `pt_BR` and `pt-PT` both read the `pt` table."""
    return (language or "en").lower().replace("_", "-").split("-")[0]


def tr(source, language=None):
    if language is None:
        from anki.lang import current_lang
        language = current_lang
    return TABLES.get(language_code(language), {}).get(source, source)
